import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { readLocalPluginPath } from "./scripts/local-build-env.mjs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";
const BUILD_DIR = "./build";
const TEST_VAULT_PLUGIN_DIR = readLocalPluginPath();
const FILES_TO_COPY = ["manifest.json", "styles.css"];

/** Copy the release assets into build/ and, when configured, into the test vault. */
function copyFiles(destDir) {
	if (destDir && !fs.existsSync(destDir)) {
		fs.mkdirSync(destDir, { recursive: true });
	}
	const mainJs = path.join(BUILD_DIR, "main.js");
	if (destDir && fs.existsSync(mainJs)) {
		fs.copyFileSync(mainJs, path.join(destDir, "main.js"));
		console.log(`Copied main.js to ${destDir}`);
	}
	for (const file of FILES_TO_COPY) {
		fs.copyFileSync(file, path.join(BUILD_DIR, file));
		if (destDir) {
			fs.copyFileSync(file, path.join(destDir, file));
		}
	}
}

const copyPlugin = {
	name: "copy-plugin",
	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length === 0) {
				copyFiles(TEST_VAULT_PLUGIN_DIR);
			}
		});
	},
};

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: ["obsidian", "electron", ...builtinModules],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: path.join(BUILD_DIR, "main.js"),
	minify: prod,
	plugins: [copyPlugin],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
